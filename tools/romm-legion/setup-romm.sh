#!/usr/bin/env bash
# tools/romm-legion/setup-romm.sh — RomM on the Legion Go (Bazzite), rootless
# Podman, started and kept up by the user's own systemd.
#
#   # on the Legion:
#   bash setup-romm.sh                      # library at ~/Emulation (EmuDeck layout)
#   ROMM_LIBRARY=/run/media/sd/Emulation bash setup-romm.sh
#   bash setup-romm.sh --open-firewall      # also open the port for the LAN (sudo)
#
#   # from another machine, once the Legion answers over the tailnet:
#   ssh daniel@bazzite 'bash -s' < tools/romm-legion/setup-romm.sh
#
# WHAT IT LAYS DOWN — nothing outside $HOME unless --open-firewall is given:
#   ~/.config/romm/romm.env         the three secrets, generated once (0600)
#   ~/.config/romm/config.yml       RomM's own config: EmuDeck folder names
#                                   mapped onto RomM's platform slugs
#   ~/.config/containers/systemd/   three Quadlet units: romm.network,
#                                   romm-db.container (MariaDB), romm.container
#   ~/Emulation/roms/<platform>/    the library RomM scans (created if absent)
#   ~/Emulation/bios/               firmware
#   ~/Emulation/romm-assets/        saves, states and screenshots uploaded
#                                   through RomM — kept out of EmuDeck's own
#
# WHY QUADLETS AND NOT podman-compose. Bazzite is Fedora Atomic: podman is
# there, podman-compose is not, and layering packages is the thing the image
# asks you not to do. Quadlet is podman's own systemd integration — a
# .container file is a unit — so the stack starts at login, restarts when it
# falls over, and `podman auto-update` can follow the registry, all without a
# compose binary. The user's manager runs it, which is why linger is enabled:
# without it the services stop the moment the last session logs out, and a
# handheld in Game Mode is exactly a machine with no session to speak of.
#
# WHY THE LIBRARY IS ~/Emulation. RomM's "structure A" is library/roms/<slug>
# and library/bios/<slug>, and EmuDeck's tree is ~/Emulation/roms/<folder> and
# ~/Emulation/bios — the same shape, so the EmuDeck root IS the library, and
# the ROMs every emulator on the handheld already plays are what RomM
# catalogues. The folder names differ for a dozen systems (EmuDeck says
# `dreamcast`, RomM says `dc`); config.yml carries the aliases. A folder RomM
# still does not know is listed under "unmatched" in its UI, not lost.
#
# SELINUX. Bazzite enforces. Mounting the user's own tree into a rootless
# container normally needs a :Z relabel, which would relabel every ROM to
# container_file_t — harmless to EmuDeck, but a surprise. SecurityLabelDisable
# turns the container's label confinement off instead, the same thing
# `--security-opt label=disable` does, and leaves the files as they are.
#
# RomM itself: https://docs.romm.app — the compose example this mirrors is
# rommapp/romm examples/docker-compose.example.yml (romm + mariadb; the
# redis it needs is inside the romm image since 3.x).

set -euo pipefail

OPEN_FIREWALL=0
for arg in "$@"; do
  case "$arg" in
    --open-firewall) OPEN_FIREWALL=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

LIB="${ROMM_LIBRARY:-$HOME/Emulation}"
ASSETS="${ROMM_ASSETS:-$LIB/romm-assets}"
CONF="$HOME/.config/romm"
QUAD="$HOME/.config/containers/systemd"
PORT="${ROMM_PORT:-8080}"
ROMM_IMAGE="${ROMM_IMAGE:-docker.io/rommapp/romm:latest}"
DB_IMAGE="${DB_IMAGE:-docker.io/library/mariadb:11}"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

command -v podman >/dev/null || die "podman is not on PATH (Bazzite ships it; is this Bazzite?)"
command -v systemctl >/dev/null || die "no systemctl: this needs a systemd user session"
command -v openssl >/dev/null || die "openssl is needed to generate the secrets"
podman info --format '{{.Host.Security.Rootless}}' 2>/dev/null | grep -q true \
  || say "note: podman reports a non-rootless setup; this script expects to run as your own user"

say "library : $LIB   (roms/<platform>, bios/)"
say "assets  : $ASSETS"
say "config  : $CONF"
say "units   : $QUAD"
say "port    : $PORT"

mkdir -p "$LIB/roms" "$LIB/bios" "$ASSETS" "$CONF" "$QUAD"

# ── secrets, generated once ──────────────────────────────────────────────────
if [ ! -f "$CONF/romm.env" ]; then
  DB_PW="$(openssl rand -hex 16)"
  (
    umask 077
    cat > "$CONF/romm.env" <<EOF
# generated by setup-romm.sh — the romm and romm-db units both read this file
DB_PASSWD=$DB_PW
MARIADB_PASSWORD=$DB_PW
MARIADB_ROOT_PASSWORD=$(openssl rand -hex 16)
ROMM_AUTH_SECRET_KEY=$(openssl rand -hex 32)
# optional metadata providers — fill in and \`systemctl --user restart romm\`
#SCREENSCRAPER_USER=
#SCREENSCRAPER_PASSWORD=
#RETROACHIEVEMENTS_API_KEY=
#STEAMGRIDDB_API_KEY=
#IGDB_CLIENT_ID=
#IGDB_CLIENT_SECRET=
EOF
  )
  say "wrote $CONF/romm.env (new secrets)"
else
  say "keeping $CONF/romm.env"
fi

# ── RomM's config: EmuDeck folder names → RomM platform slugs ────────────────
if [ ! -f "$CONF/config.yml" ]; then
  cat > "$CONF/config.yml" <<'EOF'
# RomM config — written by setup-romm.sh; RomM reads it from /romm/config.
# system.platforms maps a FOLDER NAME under roms/ to the RomM platform slug it
# stands for. EmuDeck's names are on the left where they differ from RomM's;
# folders already named by slug (snes, nes, n64, psx, ps2, psp, gba, gb, gbc,
# nds, 3ds, wii, switch, saturn, arcade, atari2600, atari7800, dos, xbox) need
# no entry. A folder RomM cannot place shows under "unmatched" in its UI —
# add a line here and rescan.
system:
  platforms:
    gc: ngc
    gamecube: ngc
    dreamcast: dc
    genesis: genesis-slash-megadrive
    megadrive: genesis-slash-megadrive
    mastersystem: sms
    gamegear: gamegear
    sega32x: sega32
    segacd: segacd
    neogeo: neogeoaes
    mame: arcade
    fbneo: arcade
    tg16: turbografx16--1
    pcengine: turbografx16--1
    tgcd: turbografx-16-slash-pc-engine-cd
    pcenginecd: turbografx-16-slash-pc-engine-cd
    atarilynx: lynx
    ps1: psx
    ps3: ps3
    psvita: psvita
    wiiu: wiiu
    n3ds: 3ds
    scummvm: scummvm
exclude:
  platforms: [cloud, dos-emudeck, model2, model3, emulators, tools]
  roms:
    single_file:
      extensions: [xml, txt, nfo, srm, sav, state, auto, m3u.bak]
      names: [info.txt, gamelist.xml, ._*, "*.nfo", systeminfo.txt, readme.txt]
    multi_file:
      names: [media, downloaded_media, images, videos, manuals, covers, screenshots, 3dboxes, marquees, miximages, titlescreens, fanart, backcovers, physicalmedia]
EOF
  say "wrote $CONF/config.yml"
else
  say "keeping $CONF/config.yml"
fi

# ── the units ────────────────────────────────────────────────────────────────
cat > "$QUAD/romm.network" <<'EOF'
# the private network romm and romm-db talk on; the name "romm-db" resolves on it
[Network]
EOF

cat > "$QUAD/romm-db.container" <<EOF
[Unit]
Description=RomM database (MariaDB)

[Container]
Image=$DB_IMAGE
ContainerName=romm-db
Network=romm.network
EnvironmentFile=$CONF/romm.env
Environment=MARIADB_DATABASE=romm
Environment=MARIADB_USER=romm-user
Volume=romm-mysql:/var/lib/mysql
HealthCmd=healthcheck.sh --connect --innodb_initialized
HealthInterval=10s
HealthTimeout=5s
HealthRetries=5
HealthStartPeriod=30s

[Service]
Restart=always
TimeoutStartSec=300

[Install]
WantedBy=default.target
EOF

cat > "$QUAD/romm.container" <<EOF
[Unit]
Description=RomM (ROM manager)
Requires=romm-db.service
After=romm-db.service

[Container]
Image=$ROMM_IMAGE
ContainerName=romm
Network=romm.network
EnvironmentFile=$CONF/romm.env
Environment=DB_HOST=romm-db
Environment=DB_NAME=romm
Environment=DB_USER=romm-user
Environment=HASHEOUS_API_ENABLED=true
Environment=SCAN_WORKERS=2
Environment=WEB_SERVER_CONCURRENCY=2
PublishPort=$PORT:8080
Volume=romm-resources:/romm/resources
Volume=romm-redis:/redis-data
Volume=$LIB:/romm/library
Volume=$ASSETS:/romm/assets
Volume=$CONF:/romm/config
SecurityLabelDisable=true
AutoUpdate=registry

[Service]
Restart=always
TimeoutStartSec=900

[Install]
WantedBy=default.target
EOF
say "wrote $QUAD/{romm.network,romm-db.container,romm.container}"

# ── start, and keep starting ─────────────────────────────────────────────────
if command -v loginctl >/dev/null; then
  loginctl enable-linger "$USER" 2>/dev/null \
    && say "linger enabled for $USER (the stack outlives the login session)" \
    || say "note: could not enable linger; the stack runs while you are logged in"
fi
systemctl --user daemon-reload
systemctl --user start romm-db.service
systemctl --user start romm.service
say "started romm-db.service and romm.service"

if [ "$OPEN_FIREWALL" = 1 ] && command -v firewall-cmd >/dev/null; then
  if sudo firewall-cmd --permanent --add-port="$PORT/tcp" && sudo firewall-cmd --reload; then
    say "opened $PORT/tcp in firewalld"
  else
    say "note: could not open $PORT/tcp (sudo?); the tailnet still reaches it"
  fi
fi

# ── where it is ──────────────────────────────────────────────────────────────
say ""
say "RomM is coming up (the first start pulls two images and runs migrations;"
say "give it a minute). Then open one of:"
say "  http://localhost:$PORT/"
HOST_NAME="$(hostname 2>/dev/null || true)"
[ -n "$HOST_NAME" ] && say "  http://$HOST_NAME:$PORT/"
if command -v tailscale >/dev/null; then
  TS_IP="$(tailscale ip -4 2>/dev/null | head -1 || true)"
  [ -n "$TS_IP" ] && say "  http://$TS_IP:$PORT/   (tailnet)"
fi
say ""
say "The first visit runs RomM's setup wizard: create the admin user there, then"
say "Scan. Put ROMs under $LIB/roms/<platform>/ (snes, nes, n64, psx, ps2, ...)."
say ""
say "  systemctl --user status romm romm-db     # health"
say "  journalctl --user -u romm -f             # logs"
say "  podman auto-update                       # follow the registry"
say "  systemctl --user stop romm romm-db       # stop (the data volumes stay)"
