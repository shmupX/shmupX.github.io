// tools/sfc-sav/factory-data.ts — regenerate src/sfc/factory-data.js from the
// factory sample save.
//
//   deno run -A tools/sfc-sav/factory-data.ts [--sav dev-fixtures/debug-tools/Dez\ SNES.sav]
//
// The sample (the ROM's own default SRAM image, committed as
// dev-fixtures/debug-tools/Dez SNES.sav) is the only known-good source of the
// regions a writer cannot compose from a level: the 11,776-byte SOUND DATA
// stream and its BGM PATCH, the editor's colour-picker palette rows, the
// RESERVED bytes and the configuration words. This writes them out as a
// module the engine bundle can carry, base64 for the big one, so the writer
// needs neither the ROM nor the fixture at run time.

import { encodeBase64 } from "@std/encoding/base64";
import { resolve } from "@std/path";
import { REGION } from "../../packages/shmup-engine/src/sfc/regions.js";
import { repoRoot } from "../../packages/shmup-harbor/lib/repo-root.ts";

const ROOT = repoRoot();
let savPath = resolve(ROOT, "dev-fixtures/debug-tools/Dez SNES.sav");
const args = Deno.args.slice();
while (args.length) {
  const a = args.shift()!;
  if (a === "--sav") savPath = resolve(args.shift()!);
  else throw new Error(`unknown argument ${a}`);
}
const sav = await Deno.readFile(savPath);
if (sav.length < 0x10000) {
  throw new Error(`${savPath}: not an SRAM dump (${sav.length} bytes)`);
}

const slice = (r: { offset: number; end: number }) =>
  sav.subarray(r.offset, r.end);
const hexList = (bytes: Uint8Array, perLine = 16) => {
  const out: string[] = [];
  for (let i = 0; i < bytes.length; i += perLine) {
    out.push(
      "    " + Array.from(bytes.subarray(i, i + perLine), (b) =>
        "0x" + b.toString(16).padStart(2, "0")).join(", ") +
        ",",
    );
  }
  return out.join("\n");
};
const u16 = (at: number) => sav[at] | (sav[at + 1] << 8);

const sound = slice(REGION.sound);
const b64 = encodeBase64(sound);
const lines: string[] = [];
for (let i = 0; i < b64.length; i += 100) {
  lines.push(`    "${b64.slice(i, i + 100)}",`);
}

const out =
  `// GENERATED by tools/sfc-sav/factory-data.ts from the factory sample save
// (the ROM's own default SRAM image) — do not edit by hand.
//
// The regions of a Super Famicom Dezaemon save a writer takes from the
// factory game rather than composing from a level: the SOUND DATA stream
// (its format is open; the sample's songs play) and the BGM PATCH that goes
// with it, the editor's colour-picker rows 22-23 of PALETTE DATA, the two
// RESERVED ranges as the game formats them, the configuration words, the
// factory ship sheet with the palette rows that colour it, and the sample's
// stage-0 boss block as a behaviour template.
// Environment-neutral ESM (Node + browser).

/** SOUND DATA (0x${
    REGION.sound.offset.toString(16)
  }, ${sound.length} bytes), base64. */
const SFC_FACTORY_SOUND_BASE64 = [
${lines.join("\n")}
].join("");

let soundBytes = null;
/** The factory sample's SOUND DATA as bytes (decoded once, then shared — copy before editing). */
export function sfcFactorySound() {
    if (!soundBytes) {
        const bin = typeof atob === "function" ? atob(SFC_FACTORY_SOUND_BASE64) : Buffer.from(SFC_FACTORY_SOUND_BASE64, "base64").toString("latin1");
        soundBytes = new Uint8Array(bin.length);
        for (let i = 0; i < bin.length; i++) soundBytes[i] = bin.charCodeAt(i);
    }
    return soundBytes;
}

/** BGM PATCH: one instrument per BGM slot, as the sample has them. */
export const SFC_FACTORY_BGM_PATCH = Object.freeze([
${hexList(slice(REGION.bgmPatch))}
]);

/** PALETTE DATA rows 22 and 23: the editor's R/G/B ramps and primaries, bit-15 tails included. */
export const SFC_FACTORY_PICKER_ROWS = Object.freeze([
${hexList(sav.subarray(REGION.palette.offset + 22 * 32, REGION.palette.end))}
]);

/** RESERVED 0x20-0x3F as formatted: zero but for the word at 0x3E. */
export const SFC_FACTORY_RESERVED0 = Object.freeze([
${hexList(slice(REGION.reserved0))}
]);

/** RESERVED 0x7FD2-0x7FF7 as formatted. */
export const SFC_FACTORY_RESERVED1 = Object.freeze([
${hexList(slice(REGION.reserved1))}
]);

/** MY SHIP GROUP: the factory ship sheet's 64 chip words (the ROM's art — the game reads it at play time). */
export const SFC_FACTORY_SHIP_WORDS = Object.freeze([
${
    (() => {
      const w = [];
      for (let i = 0; i < 64; i++) {
        w.push(u16(REGION.myShipGroup.offset + i * 2));
      }
      const lines: string[] = [];
      for (let i = 0; i < 64; i += 8) {
        lines.push(
          "    " +
            w.slice(i, i + 8).map((v) => "0x" + v.toString(16).padStart(4, "0"))
              .join(", ") +
            ",",
        );
      }
      return lines.join("\n");
    })()
  }
]);

/** PALETTE DATA rows 18-21 (ship, title, items, free), which colour the factory ship sheet. */
export const SFC_FACTORY_GLOBAL_ROWS = Object.freeze([
${
    hexList(
      sav.subarray(
        REGION.palette.offset + 18 * 32,
        REGION.palette.offset + 22 * 32,
      ),
    )
  }
]);

/** The sample's stage-0 boss block (+0x1E0): a tall boss, 4,000 hit points, three shot phases. */
export const SFC_FACTORY_BOSS_BLOCK = Object.freeze([
${
    hexList(
      sav.subarray(
        REGION.enemyData.offset + 0x1e0,
        REGION.enemyData.offset + 0x200,
      ),
    )
  }
]);

export const SFC_FACTORY_TITLE_TYPE = 0x${
    u16(REGION.titleType.offset).toString(16).padStart(4, "0")
  };
export const SFC_FACTORY_MOUSE_SPEED = 0x${
    u16(REGION.mouseSpeed.offset).toString(16).padStart(4, "0")
  };
export const SFC_FACTORY_EDIT_BGM = 0x${
    u16(REGION.editBgm.offset).toString(16).padStart(4, "0")
  };
/** KEY CONFIG: the four controller bytes. */
export const SFC_FACTORY_KEY_CONFIG = Object.freeze([${
    Array.from(slice(REGION.keyConfig), (b) =>
      "0x" + b.toString(16).padStart(2, "0")).join(", ")
  }]);
`;
const target = resolve(ROOT, "packages/shmup-engine/src/sfc/factory-data.js");
await Deno.writeTextFile(target, out);
console.log(`wrote ${target} (${out.length} chars; sound ${sound.length} B)`);
