// tools/psx-sav/plus-factory-data.ts — regenerate src/psx/plus-factory-data.js
// from Athena's sample game on the Dezaemon Plus Select 100 disc.
//
//   deno run -A tools/psx-sav/plus-factory-data.ts [--disc <Select 100 .bin>]
//
// The disc's UPLOAD/ folder holds the sample game split by section (G the
// graphics and palettes, K the stages and the global block). It is the only
// known-good source of what a Dezaemon+ writer cannot compose from a level:
// the rest of the MY SHIP sheet — the enemy bullets, the explosions, the
// items, the player's shot, the missiles (FORMAT-PSX.md "The sprite
// sheets") — and palette rows 20-23 that colour it. This writes the tiles
// those words name and the rows out as a module the engine bundle can carry,
// so the writer needs no disc at run time.

import { encodeBase64 } from "@std/encoding/base64";
import { resolve } from "@std/path";
import {
  openDisc,
  readFile,
} from "../../packages/shmup-engine/src/cd/iso9660-read.js";
import {
  PLUS_GLOBAL_LAYOUT,
  PLUS_STAGE_SIZE,
  PLUS_STAGES,
} from "../../packages/shmup-engine/src/psx/plus.js";
import { repoRoot } from "../../packages/shmup-harbor/lib/repo-root.ts";
import { findPsxDisc } from "../../lib/dezaemon-psx.ts";

const ROOT = repoRoot();
let discPath: string | null = null;
const args = Deno.args.slice();
while (args.length) {
  const a = args.shift()!;
  if (a === "--disc") discPath = resolve(args.shift()!);
  else throw new Error(`unknown argument ${a}`);
}
discPath ??= (await findPsxDisc(ROOT, "slps-01504"))?.files[0].path ?? null;
if (!discPath) {
  throw new Error(
    "no Dezaemon Plus Select 100 disc (SLPS-01504) in dev-fixtures/ — pass --disc",
  );
}
const disc = openDisc(await Deno.readFile(discPath));
const upload = (name: string): Uint8Array => {
  const bytes = readFile(disc, `UPLOAD/${name}`);
  if (!bytes) {
    throw new Error(`${discPath}: no UPLOAD/${name} — not Select 100?`);
  }
  return bytes;
};
const g = upload("SAMPG.BIN");
const k = upload("SAMPK.BIN");
const graphics = g.subarray(0, 0x10000);
const palettes = g.subarray(0x10000, 0x10300);
const piece = (name: string) => {
  // plus.js is untyped JS: its layout objects check as string | number.
  const p = PLUS_GLOBAL_LAYOUT.find((x) => x.name === name)!;
  const at = PLUS_STAGES * PLUS_STAGE_SIZE + Number(p.offset);
  return k.subarray(at, at + Number(p.length));
};
const group = piece("shipGroup");
const odr = piece("shipOdr");
if (odr.some((b) => b !== 0)) {
  throw new Error("the sample's MY SHIP ODR is not all zero");
}

// The words a writer takes from the sample: every one the program reads
// but the ship's three poses (0-11) and the three it forces (61-63) —
// 12-60, and 72-76, which build sheet row 384 while 0x80112AE3 is clear.
const FACTORY_WORDS = [
  ...Array.from({ length: 49 }, (_, i) => 12 + i),
  72,
  73,
  74,
  75,
  76,
];
const tiles: Uint8Array[] = [];
const tileOfWord = new Map<number, number>();
const shipTiles = new Array<number>(group.length / 2).fill(-1);
for (const w of FACTORY_WORDS) {
  const word = group[w * 2] | (group[w * 2 + 1] << 8);
  if ((word & 0x3ff) === 0x3ff || word & 0xc000) {
    throw new Error(`word ${w} is 0x${word.toString(16)}: blank or flipped`);
  }
  let n = tileOfWord.get(word & 0x3ff);
  if (n === undefined) {
    // The UPLOAD sample is the disc-load path's: its art names pages 2/3,
    // the save's two pages (FORMAT-PSX.md, the tile copier).
    const col = (word & 7) | ((word & 0x80) >> 4);
    const row = (word >> 3) & 15;
    const page = (word >> 8) & 1;
    const tile = new Uint8Array(128);
    for (let y = 0; y < 16; y++) {
      const at = (page * 256 + row * 16 + y) * 128 + col * 8;
      tile.set(graphics.subarray(at, at + 8), y * 8);
    }
    n = tiles.length;
    tiles.push(tile);
    tileOfWord.set(word & 0x3ff, n);
  }
  shipTiles[w] = n;
}

const sheet = new Uint8Array(tiles.length * 128);
tiles.forEach((t, i) => sheet.set(t, i * 128));
const b64 = encodeBase64(sheet);
const lines: string[] = [];
for (let i = 0; i < b64.length; i += 100) {
  lines.push(`    "${b64.slice(i, i + 100)}",`);
}
const hex4 = (w: number) => "0x" + w.toString(16).padStart(4, "0");
const row = (r: number) =>
  Array.from(
    { length: 16 },
    (_, c) =>
      hex4(palettes[r * 32 + c * 2] | (palettes[r * 32 + c * 2 + 1] << 8)),
  ).join(", ");
const shipLines: string[] = [];
for (let i = 0; i < shipTiles.length; i += 16) {
  shipLines.push("    " + shipTiles.slice(i, i + 16).join(", ") + ",");
}

const out =
  `// GENERATED by tools/psx-sav/plus-factory-data.ts from Athena's sample game
// on the Dezaemon Plus Select 100 disc (UPLOAD/SAMPG.BIN, UPLOAD/SAMPK.BIN)
// — do not edit by hand.
//
// What a Dezaemon+ writer takes from the factory game rather than composing
// from a level: the MY SHIP sheet but for the ship's three poses — the
// enemy bullets, the small and large explosions, the item capsules, the
// player's shot, the option and the missiles, all of them the save's own
// tiles named by MY SHIP GROUP (MAIN.EXE 0x8002378C; FORMAT-PSX.md "The
// sprite sheets") — and palette rows 20-23, which colour them.
// Environment-neutral ESM (Node + browser).

/** Palette rows 20-23 as the sample has them (32, 21, 91 and 103 of Select 100's 106 user games keep each as is). */
export const PLUS_FACTORY_ROWS = Object.freeze({
${
    [20, 21, 22, 23].map((r) => `    ${r}: Object.freeze([${row(r)}]),`).join(
      "\n",
    )
  }
});

/**
 * MY SHIP GROUP word i -> its tile in plusFactorySheet(), or -1 where the
 * writer composes the word itself (the poses 0-11, the forced 61-63, the
 * unread 64-71).
 */
export const PLUS_FACTORY_SHIP_TILES = Object.freeze([
${shipLines.join("\n")}
]);

/** The ${tiles.length} tiles those words name: 128 bytes each, 16 rows of 8, 4bpp, low nibble the left pixel; base64. */
const PLUS_FACTORY_SHEET_BASE64 = [
${lines.join("\n")}
].join("");

let sheetTiles = null;
/** The factory sheet's tiles as 256 palette indices each (decoded once, then shared — copy before editing). */
export function plusFactorySheet() {
    if (!sheetTiles) {
        const bin = typeof atob === "function" ? atob(PLUS_FACTORY_SHEET_BASE64) : Buffer.from(PLUS_FACTORY_SHEET_BASE64, "base64").toString("latin1");
        sheetTiles = [];
        for (let t = 0; t * 128 < bin.length; t++) {
            const tile = new Uint8Array(256);
            for (let i = 0; i < 128; i++) {
                const b = bin.charCodeAt(t * 128 + i);
                tile[i * 2] = b & 15;
                tile[i * 2 + 1] = b >> 4;
            }
            sheetTiles.push(tile);
        }
    }
    return sheetTiles;
}
`;
const target = resolve(
  ROOT,
  "packages/shmup-engine/src/psx/plus-factory-data.js",
);
await Deno.writeTextFile(target, out);
console.log(
  `wrote ${target} (${out.length} chars; ${tiles.length} tiles for ${FACTORY_WORDS.length} words)`,
);
