export const KIDS_PALETTE_SIZE = KIDS_PALETTE.length;
/** A CG pixel byte of 0 is the transparent background. */
export const KIDS_TRANSPARENT_INDEX = 0;

/**
 * The bank as {raw, r, g, b, stp, empty} entries.
 * @param {{backdrop?: boolean}} [options] `backdrop: true` swaps index 0 for
 *   the map CLUT's white, which is how the background layer draws it.
 */
export function kidsPaletteRgb({ backdrop = false } = {}) {
    return KIDS_PALETTE.map((raw, i) => {
        const word = backdrop && i === KIDS_TRANSPARENT_INDEX ? KIDS_BACKDROP_WORD : raw;
        return { raw: word, ...rgb555ToRgb(word), stp: (word & 0x8000) !== 0, empty: word === 0 };
    });
}
