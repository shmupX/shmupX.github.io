// The Dezaemon Kids! palette bank — the one part of a Kids! game that is not
// in the save.
//
// A Kids! save carries 8-bit CG pixels and no colours at all: the bank is
// G256PAL.CLT in the disc's KIDS_DAT.BIN archive, 256 PlayStation RGB555
// words that KIDS.EXE uploads once at boot as a single 256x1 VRAM row
// (0x8006a34c skips the file's 20-byte TIM-style header and calls LoadClut2
// sixteen times across x = 0..255 at y = 482), so a CG pixel byte IS the
// index into these 256 words — there is no (row << 4) | colour indirection
// as on the Saturn. The drawing code takes GetClut(0, 482) for the map and
// background strips and GetClut(0, 483) for sprites; the second row is
// G256PAL2.CLT, which differs from the first in exactly one word:
//
//   index 0 = 0xFFFF (white) in G256PAL, drawn as the map's backdrop
//   index 0 = 0x0000        in G256PAL2, drawn as transparent for sprites
//
// so `KIDS_PALETTE[0]` below is the sprite (transparent) form and
// KIDS_BACKDROP_WORD is the map form. GAMES.bin, the play-mode overlay,
// carries a byte-identical copy of G256PAL2 at 0x80148420 and derives its
// fade rows from it. Nothing a save contains can change any of this.
//
// Words are PlayStation RGB555 little-endian: R bits 0-4, G 5-9, B 10-14,
// bit 15 = STP (semi-transparency), the same channel order as the Saturn
// bank, so decode-cg.js `rgb555ToRgb` applies unchanged.
//
// Environment-neutral ESM (Node + browser).

import { rgb555ToRgb } from "../decode/decode-cg.js";

